"""The TypeScript recorder's output against the real Python service.

`fixtures/recorder/scenario-*.json` hold the `IngestRequest`s exactly as the TypeScript recorder sent
them over a fake notebook, with the fake notebook's final state. They are generated by
`src/__tests__/recording/fixtures.spec.ts` (never edited by hand; that spec fails when a file is stale,
and `BLAYM_WRITE_FIXTURES=1 npx jest src/__tests__/recording/fixtures.spec.ts` rewrites them).

Here every scenario is ingested into the service over the memory ports and over SQLite
(`open_service`): no event is refused, the notebook rebuilt at the last tick equals the fake notebook,
and sending every request a second time changes nothing.
"""

from __future__ import annotations

import json
from pathlib import Path


from blaym_notebook.local import open_service
from blaym_notebook.service.auth import FixedTokenAuthorizer
from blaym_notebook.service.core import Service
from blaym_notebook.testing.fakes import FakeClock, IdFactory
from blaym_notebook.testing.memory import MemoryBlobStore, MemoryEventStore
from blaym_notebook_types import OutlineRequest, StateAtRequest

TOKEN = "t0ken"
FIXTURES = Path(__file__).resolve().parents[5] / "fixtures" / "recorder"
FILES = sorted(FIXTURES.glob("scenario-*.json"))


def _memory(_tmp):
    return Service(MemoryEventStore(), MemoryBlobStore(), FixedTokenAuthorizer(TOKEN), FakeClock(), new_id=IdFactory("svc"))


def _sqlite(tmp):
    return open_service(tmp, FixedTokenAuthorizer(TOKEN), clock=FakeClock(), new_id=IdFactory("svc"))


def _outcomes(response):
    return [o.root if hasattr(o, "root") else o for o in response.outcomes]


def _outputs(cell) -> list[str]:
    return [item.preview for group in cell.outputs for item in group.items]


def _check_scenario(path, make, tmp_path):
    scenario = json.loads(path.read_text())
    exp = scenario["requests"][0]["explorationId"]
    service = make(tmp_path)
    try:
        for i, request in enumerate(scenario["requests"]):
            for o in _outcomes(service.ingest(TOKEN, request)):
                assert o.status == "accepted", f"request {i}: {o}"

        outline = service.outline(TOKEN, OutlineRequest(explorationId=exp))
        assert outline is not None
        branch, tick = outline.rootBranchId, outline.highestTick
        state = service.state_at(TOKEN, StateAtRequest(explorationId=exp, branchId=branch, tick=tick))
        assert state.status == "ok"
        notebook = state.state.notebook
        final = scenario["final"]
        got = [{"id": c.cellId, "type": c.cellType.value if hasattr(c.cellType, "value") else c.cellType,
                "code": c.code, "metadata": c.metadata, "outputs": _outputs(c)} for c in notebook.cells]
        # The fake notebook keeps outputs on a cell made raw; a snapshot gives a non-code cell none.
        want = [c if c["type"] == "code" else {**c, "outputs": []} for c in final["cells"]]
        assert got == want
        assert notebook.metadata == final["notebookMetadata"]

        # the second delivery of every request: nothing changes, everything is a duplicate
        for i, request in enumerate(scenario["requests"]):
            for o in _outcomes(service.ingest(TOKEN, request)):
                assert o.status == "accepted" and o.duplicate, f"request {i} again: {o}"
        again = service.outline(TOKEN, OutlineRequest(explorationId=exp))
        assert again == outline
    finally:
        if hasattr(service, "close"):
            service.close()


def test_every_scenario_ingests_and_rebuilds_to_the_fake_notebook_on_both_backends(tmp_path):
    assert FILES
    for make in (_memory, _sqlite):
        for path in FILES:
            where = tmp_path / f"{make.__name__}-{path.stem}"
            where.mkdir()
            _check_scenario(path, make, where)
